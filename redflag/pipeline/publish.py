"""Stage 10: publish archive.db for Zetaris, and build the sample database.

Writes, under data/publish/:
- parquet/<table>.parquet for every archive table, and parquet/prices/ split
  by year: upload this folder to the bucket Zetaris reads (the "files" route);
- postgres/<table>.csv plus, per Postgres database, schema-<db>.sql and
  load-<db>.sql: `run.py zetaris load-pg` loads them, and Zetaris registers
  each database over JDBC (the "postgres" route).

It also builds data/sample/archive_sample.db, the small committed subset that
sample mode serves through MockZetaris. Nothing here talks to Zetaris; the
`zetaris register` command does that (redflag/data/zetaris_setup.py).
"""
from __future__ import annotations

import csv
import os
import sqlite3

import pyarrow as pa
import pyarrow.parquet as pq

from redflag.common.db import SCHEMA, _migrate
from redflag.pipeline.base import Gate, StageContext

TABLES = ["ipos", "bankers", "banker_alias", "ipo_banker", "trading_days", "prices",
          "corp_actions", "labels", "sebi_orders", "sebi_order_entity", "entities",
          "entity_alias", "entity_edge", "docs", "facts", "features"]
PG_TYPES = {"INTEGER": "BIGINT", "REAL": "DOUBLE PRECISION", "TEXT": "TEXT", "": "TEXT"}
# Postgres route: one database per Zetaris source (<db>_archive, <db>_live,
# <db>_prices), tables in `public`, because Zetaris discovers only `public`.
PG_DATABASES = {"archive": [t for t in TABLES if t != "prices"],
                "live": ["sebi_orders", "sebi_order_entity"],
                "prices": ["prices"]}
# Demo IPOs for sample mode; their bankers' full histories come along.
DEFAULT_SAMPLE = "NSE-2023-SYNOPTICS"


def run(ctx: StageContext) -> dict:
    out = ctx.settings.data / "publish"
    rows = {}
    for table in TABLES:
        rows[table] = write_parquet(ctx.conn, table, out / "parquet")
        write_csv(ctx.conn, table, out / "postgres" / f"{table}.csv")
    write_postgres_sql(ctx.conn, out / "postgres")
    sample = build_sample(ctx)
    ctx.log.info(f"published {len(TABLES)} tables; sample db has {sample} IPOs",
                 rows=rows)
    return {"tables": len(TABLES), "sample_ipos": sample}


def _columns(conn, table: str) -> list[tuple[str, str]]:
    return [(r["name"], r["type"].upper()) for r in conn.execute(f"PRAGMA table_info({table})")]


def _arrow_type(sql_type: str):
    return {"INTEGER": pa.int64(), "REAL": pa.float64()}.get(sql_type, pa.string())


def write_parquet(conn, table: str, out) -> int:
    cols = _columns(conn, table)
    schema = pa.schema([(c, _arrow_type(t)) for c, t in cols])
    data = conn.execute(f"SELECT * FROM {table}").fetchall()
    if table == "prices":
        # Partition by year so Zetaris scans only the years a query needs.
        by_year: dict[str, list] = {}
        for r in data:
            by_year.setdefault(r["date"][:4], []).append(r)
        for year, part in by_year.items():
            path = out / "prices" / f"year={year}" / "prices.parquet"
            path.parent.mkdir(parents=True, exist_ok=True)
            pq.write_table(_to_table(part, cols, schema), path)
    else:
        out.mkdir(parents=True, exist_ok=True)
        pq.write_table(_to_table(data, cols, schema), out / f"{table}.parquet")
    return len(data)


def _to_table(rows, cols, schema) -> pa.Table:
    return pa.table({c: [r[c] for r in rows] for c, _ in cols}, schema=schema)


def write_csv(conn, table: str, path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    cur = conn.execute(f"SELECT * FROM {table}")
    with path.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow([d[0] for d in cur.description])
        w.writerows(cur)


def write_postgres_sql(conn, out) -> None:
    """Per database: DDL (schema-<db>.sql) and psql \\copy lines (load-<db>.sql).

    `live` holds fresh per-run lookups with the archive's shape, so it is
    created if missing and never reloaded.
    """
    for db, tables in PG_DATABASES.items():
        ddl = ["-- Generated by run.py publish. Load with: python run.py zetaris load-pg"]
        load = []
        for table in tables:
            cols = ",\n  ".join(f"{c} {PG_TYPES.get(t, 'TEXT')}" for c, t in _columns(conn, table))
            if db == "live":
                ddl.append(f"CREATE TABLE IF NOT EXISTS {table} (\n  {cols}\n);")
                continue
            ddl.append(f"DROP TABLE IF EXISTS {table};\nCREATE TABLE {table} (\n  {cols}\n);")
            load.append(f"\\copy {table} FROM '{table}.csv' WITH (FORMAT csv, HEADER true)")
        (out / f"schema-{db}.sql").write_text("\n\n".join(ddl) + "\n")
        (out / f"load-{db}.sql").write_text("".join(line + "\n" for line in load))


def build_sample(ctx: StageContext) -> int:
    """A small archive for sample mode: demo IPOs plus their bankers' histories."""
    demo = [i.strip() for i in os.environ.get("SAMPLE_IPOS", DEFAULT_SAMPLE).split(",")]
    path = ctx.settings.data / "sample" / "archive_sample.db"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.unlink(missing_ok=True)
    ctx.conn.commit()
    sample = sqlite3.connect(path)
    sample.row_factory = sqlite3.Row
    sample.executescript(SCHEMA.read_text())
    _migrate(sample)          # the same added columns as archive.db
    sample.execute("ATTACH DATABASE ? AS src", (str(ctx.settings.archive_db),))
    marks = ",".join("?" * len(demo))
    sample.execute(f"""CREATE TEMP TABLE keep AS
        SELECT DISTINCT ib2.ipo_id FROM src.ipo_banker ib
        JOIN src.ipo_banker ib2 ON ib2.banker_id = ib.banker_id
        WHERE ib.ipo_id IN ({marks})
        UNION SELECT ipo_id FROM src.ipos WHERE ipo_id IN ({marks})""", demo + demo)
    copies = {
        "ipos": "SELECT * FROM src.ipos WHERE ipo_id IN (SELECT ipo_id FROM keep)",
        "ipo_banker": "SELECT * FROM src.ipo_banker WHERE ipo_id IN (SELECT ipo_id FROM keep)",
        "bankers": "SELECT * FROM src.bankers WHERE banker_id IN "
                   "(SELECT banker_id FROM src.ipo_banker WHERE ipo_id IN (SELECT ipo_id FROM keep))",
        "banker_alias": "SELECT * FROM src.banker_alias WHERE banker_id IN "
                        "(SELECT banker_id FROM src.ipo_banker WHERE ipo_id IN (SELECT ipo_id FROM keep))",
        "labels": "SELECT * FROM src.labels WHERE ipo_id IN (SELECT ipo_id FROM keep)",
        "trading_days": "SELECT * FROM src.trading_days",
        "prices": "SELECT * FROM src.prices WHERE symbol IN "
                  "(SELECT symbol FROM src.ipos WHERE ipo_id IN (SELECT ipo_id FROM keep))",
        "corp_actions": "SELECT * FROM src.corp_actions WHERE symbol IN "
                        "(SELECT symbol FROM src.ipos WHERE ipo_id IN (SELECT ipo_id FROM keep))",
        "entities": "SELECT * FROM src.entities",
        "entity_alias": "SELECT * FROM src.entity_alias",
        "sebi_orders": "SELECT * FROM src.sebi_orders",
        "sebi_order_entity": "SELECT * FROM src.sebi_order_entity",
        "features": "SELECT * FROM src.features WHERE ipo_id IN (SELECT ipo_id FROM keep)",
    }
    for table, select in copies.items():
        # Copy by column name: migrated columns may sit in a different order.
        cols = ", ".join(c for c, _ in _columns(sample, table))
        sample.execute(f"INSERT INTO {table} ({cols}) "
                       + select.replace("SELECT *", f"SELECT {cols}", 1))
    sample.commit()
    n = sample.execute("SELECT count(*) FROM ipos").fetchone()[0]
    sample.close()
    return n


def gate(conn, settings) -> Gate:
    g = Gate("publish")
    out = settings.data / "publish"
    g.add("parquet written", (out / "parquet" / "ipos.parquet").exists(), str(out / "parquet"))
    g.add("postgres load files", all((out / "postgres" / f"load-{db}.sql").exists()
                                     for db in PG_DATABASES), str(out / "postgres"))
    sample = settings.data / "sample" / "archive_sample.db"
    g.add("sample db", sample.exists(), str(sample))
    return g
